using System.Diagnostics;
using System.Windows;

namespace RAMSOfficial;

public partial class WaitingForReaderWindow : Window
{
    public WaitingForReaderWindow()
    {
        InitializeComponent();
        
        Debug.WriteLine("???????????????????????????????????????????");
        Debug.WriteLine("  WAITING FOR READER WINDOW OPENED");
        Debug.WriteLine("???????????????????????????????????????????");
    }

    private void Window_SourceInitialized(object? sender, EventArgs e)
    {
        // Set window to cover full screen (windowed fullscreen) using WPF SystemParameters
        this.Left = 0;
        this.Top = 0;
        this.Width = SystemParameters.PrimaryScreenWidth;
        this.Height = SystemParameters.PrimaryScreenHeight;
        
        Debug.WriteLine($"? Windowed fullscreen: {SystemParameters.PrimaryScreenWidth}x{SystemParameters.PrimaryScreenHeight}");
    }

    protected override void OnKeyDown(System.Windows.Input.KeyEventArgs e)
    {
        base.OnKeyDown(e);
        if (e.Key == System.Windows.Input.Key.P)
        {
            if (Application.Current is App app)
            {
                app.SkipReaderCheck();
            }
        }
    }

    protected override void OnClosed(EventArgs e)
    {
        base.OnClosed(e);
        
        Debug.WriteLine("???????????????????????????????????????");
        Debug.WriteLine("  WAITING FOR READER WINDOW CLOSED");
        Debug.WriteLine("???????????????????????????????????????");
    }
}
