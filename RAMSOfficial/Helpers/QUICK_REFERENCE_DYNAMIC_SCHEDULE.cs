    {
        // DynamicScheduleUpdateResult properties:
        var result = new DynamicScheduleUpdateResult
        {
            Success = true,
            HasActiveTimeIn = true,
            OriginalExpectedTimeOut = new TimeSpan(11, 0, 0),
            NewExpectedTimeOut = new TimeSpan(15, 0, 0),
            ScheduleChanged = true,
            TimeExtensionMinutes = 240
        };
        
        Console.WriteLine($"Success: {result.Success}");
        Console.WriteLine($"Has Active Time IN: {result.HasActiveTimeIn}");
        Console.WriteLine($"Schedule Changed: {result.ScheduleChanged}");
        Console.WriteLine($"Time Extended By: {result.TimeExtensionMinutes} minutes");
        Console.WriteLine($"Summary: {result.GetSummary()}");
        
        // CurrentScheduleInfo properties:
        var schedule = new CurrentScheduleInfo
        {
            HasSchedule = true,
            ExpectedTimeIn = new TimeSpan(8, 0, 0),
            ExpectedTimeOut = new TimeSpan(15, 0, 0)
        };
        
        // Add substitute duties to trigger HasSubstituteDuties property
        schedule.SubstituteDuties.Add(new ScheduleTimeSlot
        {
            StartTime = new TimeSpan(12, 0, 0),
            EndTime = new TimeSpan(15, 0, 0),
            IsSubstituteDuty = true
        });
        
        Console.WriteLine($"Expected Time IN: {schedule.ExpectedTimeIn:hh\\:mm}");
        Console.WriteLine($"Expected Time OUT: {schedule.ExpectedTimeOut:hh\\:mm}");
        Console.WriteLine($"Has Substitute Duties: {schedule.HasSubstituteDuties}");
        Console.WriteLine($"Display: {schedule.GetScheduleDisplay()}");
    }

