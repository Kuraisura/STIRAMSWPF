// Solution: Automatically update their expected Time OUT in real-time
// ????????????????????????????????????????????????????????????????????????????????

using System;
using System.Threading.Tasks;
using RAMSOfficial.Helpers;
using Dapper;

namespace RAMSOfficial.Examples;

public static class DynamicScheduleQuickReference
{
    // ????????????????????????????????????????????????????????????????????????????????
    // SCENARIO
    // ????????????????????????????????????????????????????????????????????????????????
    
    /*
     * BRIAN MATTHEW ALCALA:
     *   Original Schedule: 8:00 AM - 11:00 AM (Math 101)
     *   Status: ? Already tapped IN at 8:00 AM
     * 
     * MARK CRYSLER BADDO:
     *   Original Schedule: 12:00 PM - 3:00 PM (Physics 102)
     *   Action: Requests substitution ? Approved ? Assigned to Brian
     * 
     * EXPECTED BEHAVIOR:
     *   Brian's schedule updates from 8:00-11:00 to 8:00-3:00 PM
     *   When Brian taps out, validate against 3:00 PM (not 11:00 AM)
     */

    // ????????????????????????????????????????????????????????????????????????????????
    // USAGE 1: When Substitution is Approved
    // ????????????????????????????????????????????????????????????????????????????????
    
    public static async Task UpdateScheduleWhenSubstitutionApproved(
        int substituteEmployeeId,
        DateTime substitutionDate,
        TimeSpan dutyStartTime,
        TimeSpan dutyEndTime,
        string connectionString)
    {
        var updater = new DynamicScheduleUpdater(connectionString);
        
        // Update the employee's active attendance record
        var result = await updater.UpdateActiveAttendanceScheduleAsync(
            substituteEmployeeId,
            substitutionDate,
            dutyStartTime,
            dutyEndTime
        );
        
        if (result.Success && result.ScheduleChanged)
        {
            Console.WriteLine($"? Schedule updated!");
            Console.WriteLine($"  Original: {result.OriginalExpectedTimeOut:hh\\:mm}");
            Console.WriteLine($"  New:      {result.NewExpectedTimeOut:hh\\:mm}");
            Console.WriteLine($"  Extended: +{result.TimeExtensionMinutes} minutes");
        }
        else
        {
            Console.WriteLine($"? {result.Message}");
        }
    }

    // ????????????????????????????????????????????????????????????????????????????????
    // USAGE 2: Get Current Expected Schedule (for Time OUT validation)
    // ????????????????????????????????????????????????????????????????????????????????
    
    public static async Task<TimeSpan?> GetExpectedTimeOut(
        int employeeId,
        DateTime date,
        string connectionString)
    {
        var updater = new DynamicScheduleUpdater(connectionString);
        
        var schedule = await updater.GetCurrentExpectedScheduleAsync(employeeId, date);
        
        if (schedule.HasSchedule)
        {
            return schedule.ExpectedTimeOut;
        }
        
        return null;
    }

    // ????????????????????????????????????????????????????????????????????????????????
    // USAGE 3: Validate Time OUT Against Dynamic Schedule
    // ????????????????????????????????????????????????????????????????????????????????
    
    public static async Task<(bool isOnTime, int undertimeMinutes)> ValidateTimeOut(
        int employeeId,
        DateTime tapTime,
        string connectionString)
    {
        var updater = new DynamicScheduleUpdater(connectionString);
        
        // Get CURRENT expected schedule (includes substitute duties)
        var schedule = await updater.GetCurrentExpectedScheduleAsync(employeeId, tapTime.Date);
        
        if (!schedule.HasSchedule)
        {
            return (true, 0); // No schedule, allow
        }

        if (!schedule.ExpectedTimeOut.HasValue)
        {
            return (true, 0); // Schedule exists but no expected out time
        }
        
        var expectedOut = schedule.ExpectedTimeOut.Value;
        var actualOut = tapTime.TimeOfDay;
        
        if (actualOut < expectedOut)
        {
            // Undertime
            var undertimeMinutes = (int)(expectedOut - actualOut).TotalMinutes;
            return (false, undertimeMinutes);
        }
        else
        {
            // On time (stayed until or after expected)
            return (true, 0);
        }
    }

    // ????????????????????????????????????????????????????????????????????????????????
    // INTEGRATION EXAMPLE: Substitution Approval Handler
    // ????????????????????????????????????????????????????????????????????????????????
    
    public static async Task ApproveSubstitutionWithScheduleUpdate(
        long substitutionId,
        int substituteEmployeeId,
        DateTime substitutionDate,
        TimeSpan startTime,
        TimeSpan endTime,
        int approvedBy,
        string connectionString)
    {
        using var connection = new Npgsql.NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        
        // Step 1: Update substitution status to approved
        await connection.ExecuteAsync(@"
            UPDATE class_substitutions_v2
            SET status = 'approved',
                approved_by = @ApprovedBy,
                approved_at = NOW()
            WHERE id = @SubstitutionId
        ", new { SubstitutionId = substitutionId, ApprovedBy = approvedBy });
        
        Console.WriteLine($"? Substitution {substitutionId} approved");
        
        // Step 2: Update substitute employee's active schedule
        var updater = new DynamicScheduleUpdater(connectionString);
        var result = await updater.UpdateActiveAttendanceScheduleAsync(
            substituteEmployeeId,
            substitutionDate,
            startTime,
            endTime
        );
        
        if (result.Success)
        {
            Console.WriteLine($"? {result.Message}");
            
            if (result.ScheduleChanged)
            {
                Console.WriteLine($"  Schedule extended from {result.OriginalExpectedTimeOut:hh\\:mm} to {result.NewExpectedTimeOut:hh\\:mm}");
            }
        }
        else
        {
            Console.WriteLine($"? {result.Message}");
        }
    }

    // ????????????????????????????????????????????????????????????????????????????????
    // REAL-WORLD EXAMPLE: Brian's Timeline
    // ????????????????????????????????????????????????????????????????????????????????
    
    public static async Task BrianTimelineExample(string connectionString)
    {
        int brianId = 123;
        DateTime today = DateTime.Today;
        
        Console.WriteLine("BRIAN'S TIMELINE:");
        Console.WriteLine("????????????????????????????????????????????????????????????????");
        
        // 8:00 AM - Brian taps IN
        Console.WriteLine("8:00 AM - Brian taps IN for his 8-11 AM class");
        Console.WriteLine("          Expected Time OUT: 11:00 AM");
        Console.WriteLine();
        
        // 10:30 AM - Mark's substitution is approved
        Console.WriteLine("10:30 AM - Mark's substitution (12-3 PM) APPROVED");
        Console.WriteLine("           Brian assigned as substitute");
        
        var updater = new DynamicScheduleUpdater(connectionString);
        var result = await updater.UpdateActiveAttendanceScheduleAsync(
            brianId,
            today,
            new TimeSpan(12, 0, 0),  // 12:00 PM
            new TimeSpan(15, 0, 0)   // 3:00 PM
        );
        
        if (result.ScheduleChanged)
        {
            Console.WriteLine($"           ? Brian's schedule updated!");
            Console.WriteLine($"           Expected Time OUT: {result.OriginalExpectedTimeOut:hh\\:mm} ? {result.NewExpectedTimeOut:hh\\:mm}");
        }
        Console.WriteLine();
        
        // 2:55 PM - Brian taps OUT (Undertime)
        Console.WriteLine("2:55 PM - Brian attempts to tap OUT");
        var (isOnTime1, undertime1) = await ValidateTimeOut(brianId, today.AddHours(14).AddMinutes(55), connectionString);
        Console.WriteLine($"          Result: {(isOnTime1 ? "? On Time" : $"? UNDERTIME ({undertime1} minutes)")}");
        Console.WriteLine();
        
        // 3:01 PM - Brian taps OUT (On Time)
        Console.WriteLine("3:01 PM - Brian taps OUT");
        var (isOnTime2, undertime2) = await ValidateTimeOut(brianId, today.AddHours(15).AddMinutes(1), connectionString);
        Console.WriteLine($"          Result: {(isOnTime2 ? "? On Time" : $"? UNDERTIME ({undertime2} minutes)")}");
        Console.WriteLine();
        
        Console.WriteLine("????????????????????????????????????????????????????????????????");
    }

    // ????????????????????????????????????????????????????????????????????????????????
    // KEY PROPERTIES
    // ????????????????????????????????????????????????????????????????????????????????
    
